"""
AtmosphereReader - Implements ATLAS7V READIN Subroutine

This module provides the AtmosphereReader class that reads stellar atmosphere
models in ATLAS9 format, implementing the READIN(MODE=2) algorithm from
atlas7v.for (lines 1326-1700+).

The reader follows the Fortran algorithm:
1. Reads 80-character lines sequentially
2. Extracts keywords using Machine-Independent Alphameric Code (MIAC)
3. Routes to keyword-specific handlers
4. Extracts floating-point values using FREEFF-like parsing
5. Populates an Atmosphere object
6. Stops at END keyword

Input file format (e.g., output_synthe.out):
    TEFF   5770.  GRAVITY 4.44000
    TITLE   Description...
    MOLECULES ON
    ABUNDANCE CHANGE ...
    READ DECK6 72 RHOX,T,P,...
    <72 rows of data>
    END
"""

import re
from typing import Optional, List, Union, TextIO, Tuple
from ..atmosphere import Atmosphere

# Lazy import torch only when needed
torch = None
_torch_available = False

def _ensure_torch():
    """Try to ensure torch is available, falling back to lists if not."""
    global torch, _torch_available
    if _torch_available or torch is not None:
        return torch
    
    try:
        import torch
        _torch_available = True
        return torch
    except ImportError:
        _torch_available = False
        return None

def _make_tensor(values, dtype_name="float64"):
    """Create a tensor, falling back to list if torch unavailable."""
    torch_module = _ensure_torch()
    if torch_module is not None:
        if dtype_name == "float64":
            return torch_module.tensor(values, dtype=torch_module.float64)
        elif dtype_name == "int64":
            return torch_module.tensor(values, dtype=torch_module.int64)
    return values  # Fallback to list


class AtmosphereReader:
    """Reads ATLAS stellar atmosphere models from standard card deck format.
    
    Implements MODE=2 and MODE=20 of ATLAS7V READIN subroutine, parsing
    pre-computed atmosphere models (typically generated by ATLAS9/DFSYNTHE).
    
    The reader is an event-driven parser that processes keywords sequentially,
    extracting parameters and populating an Atmosphere object.
    
    Example:
        >>> reader = AtmosphereReader()
        >>> atm = reader.read("output_synthe.out")
        >>> print(f"TEFF = {atm.TEFF} K, GRAV = {atm.GRAV:.2e}")
    """
    
    def __init__(self):
        """Initialize the atmosphere reader."""
        self.atmosphere: Optional[Atmosphere] = None
        self.file: Optional[TextIO] = None
        self.current_line: str = ""
        self.line_number: int = 0
        self.should_close: bool = False
        self.miac_cache: dict = {}  # Cache for MIAC code conversion
    
    def read(self, filepath: Union[str, TextIO]) -> Atmosphere:
        """Read an ATLAS atmosphere model from file.
        
        Args:
            filepath: Path to input file (str) or file object (TextIO)
        
        Returns:
            Atmosphere object containing parsed model data
        
        Raises:
            ValueError: If parsing fails or required fields are missing
            IOError: If file cannot be read
        """
        # Open file if needed
        if isinstance(filepath, str):
            self.file = open(filepath, 'r')
            self.should_close = True
        else:
            self.file = filepath
            self.should_close = False
        
        # Initialize atmosphere object
        self.atmosphere = Atmosphere(TEFF=0.0, GRAV=0.0, RHOX=None)
        self.line_number = 0
        
        try:
            # Main reading loop - process keywords until END
            while True:
                self.current_line = self.file.readline()
                
                if not self.current_line:
                    # EOF without END keyword
                    break
                
                self.line_number += 1
                self.current_line = self.current_line.rstrip('\n')
                
                # Skip empty lines
                if not self.current_line.strip():
                    continue
                
                # Extract keyword (first alphanumeric word)
                keyword = self._extract_keyword(self.current_line)
                
                if not keyword:
                    continue
                
                # Dispatch to appropriate handler
                if keyword == "TEFF":
                    self._handle_teff()
                elif keyword == "GRAVITY":
                    self._handle_gravity()
                elif keyword == "TITLE":
                    self._handle_title()
                elif keyword == "MOLECULES":
                    self._handle_molecules()
                elif keyword == "OPACITY":
                    self._handle_opacity()
                elif keyword == "CONVECTION":
                    self._handle_convection()
                elif keyword == "TURBULENCE":
                    self._handle_turbulence()
                elif keyword == "ABUNDANCE":
                    self._handle_abundance()
                elif keyword == "PRESSURE":
                    self._handle_pressure()
                elif keyword == "CORRECTION":
                    self._handle_correction()
                elif keyword == "SURFACE":
                    self._handle_surface()
                elif keyword == "READ":
                    self._handle_read()
                elif keyword == "LTE":
                    self._handle_lte()
                elif keyword == "NLTE":
                    self._handle_nlte()
                elif keyword == "PRADK":
                    self._handle_pradk()
                elif keyword == "END":
                    # Stop reading at END keyword
                    break
                # Ignore other keywords: ITERATIONS, WAVELENGTH, PRINT, PUNCH, SCATTERING, etc.
            
            # Validate and finalize
            self._finalize_atmosphere()
            
            return self.atmosphere
        
        finally:
            if self.should_close and self.file:
                self.file.close()
    
    # ========== Keyword Handlers ==========
    
    def _handle_teff(self):
        """Handle TEFF keyword (Effective Temperature).
        
        Fortran (atlas7v.for line 100):
            TEFF=FREEFF(CARD)
            FLUX=5.6697D-5/12.5664*TEFF**4
        
        Note: FLUX calculation is deferred to Atmosphere.update() for physics layer.
        Also handles multiple keywords on same line: "TEFF 5770. GRAVITY 4.44"
        """
        # Find "TEFF" in the line (case-insensitive) and extract value after it
        line_upper = self.current_line.upper()
        teff_pos = line_upper.find("TEFF")
        if teff_pos >= 0:
            value = self._extract_float(self.current_line, offset=teff_pos + len("TEFF"))
            if value is not None:
                self.atmosphere.TEFF = value
                # Physics calculation deferred to Atmosphere.update()
        
        # Check if GRAVITY is also on this line (case-insensitive)
        grav_pos = line_upper.find("GRAVITY")
        if grav_pos > teff_pos and grav_pos >= 0:
            self._handle_gravity_inline(grav_pos)
    
    def _handle_gravity(self):
        """Handle GRAVITY keyword.
        
        Fortran (atlas7v.for line 200):
            GRAV=FREEFF(CARD)
            IF(GRAV.LT.10.)GRAV=EXP10(GRAV)
            GLOG=LOG10(GRAV)
        """
        line_upper = self.current_line.upper()
        grav_pos = line_upper.find("GRAVITY")
        if grav_pos >= 0:
            self._handle_gravity_inline(grav_pos)
    
    def _handle_gravity_inline(self, grav_pos: int):
        """Internal helper to parse gravity value from position.
        
        Note: Physics calculations (log-to-linear conversion and GLOG computation)
        are deferred to Atmosphere.update().
        """
        value = self._extract_float(self.current_line, offset=grav_pos + len("GRAVITY"))
        if value is not None:
            # Store raw value - conversion and GLOG calculation deferred to Atmosphere.update()
            self.atmosphere.GRAV = value
    
    def _handle_title(self):
        """Handle TITLE keyword.
        
        Fortran (atlas7v.for line 1800-1801):
            DO 1801 I=1,74
            TITLE(I)=CARD(I+6)
        """
        # Extract 74 characters after "TITLE" (position 6 onward)
        start = self.current_line.find("TITLE")
        if start >= 0:
            start += len("TITLE")
            title = self.current_line[start:start+74].strip()
            self.atmosphere.TITLE = title
    
    def _handle_molecules(self):
        """Handle MOLECULES keyword.
        
        Fortran (atlas7v.for line 600):
            MIAC=IWORDF(CARD)
            IF(MIAC.EQ.569)GO TO 610    ! ON
            IF(MIAC.EQ.20763)GO TO 620  ! OFF
        """
        # Extract ON/OFF keyword
        subkeyword = self._extract_keyword(self.current_line, offset=len("MOLECULES"))
        if subkeyword == "ON":
            self.atmosphere.IFMOL = 1
        elif subkeyword == "OFF":
            self.atmosphere.IFMOL = 0
    
    def _handle_opacity(self):
        """Handle OPACITY keyword with IFOP flags.
        
        Fortran (atlas7v.for line 300-371):
            MIAC=IWORDF(CARD)
            IF(MIAC.EQ.569)GO TO 380    ! ON
            IF(MIAC.EQ.20763)GO TO 390  ! OFF
            IF(MIAC.EQ.464662)GO TO 370 ! IFOP
        """
        subkeyword = self._extract_keyword(self.current_line, offset=len("OPACITY"))
        
        if subkeyword == "IFOP":
            # Read 20 integer flags
            # Skip "OPACITY IFOP" and extract integers
            line_data = self.current_line.split()
            flags = []
            for i, item in enumerate(line_data):
                if item in ["OPACITY", "IFOP"]:
                    continue
                try:
                    flags.append(int(item))
                except ValueError:
                    pass
            
            if len(flags) >= 20:
                self.atmosphere.IFOP = _make_tensor(flags[:20], "int64")
        elif subkeyword == "ON":
            # Enable all opacities
            self.atmosphere.IFOP = _make_tensor([1] * 20, "int64")
        elif subkeyword == "OFF":
            # Disable all opacities
            self.atmosphere.IFOP = _make_tensor([0] * 20, "int64")
    
    def _handle_convection(self):
        """Handle CONVECTION keyword.
        
        Fortran (atlas7v.for line 1900):
            IFCONV=1
            MIXLTH=FREEFF(CARD)
            or
            IFCONV=0
        """
        subkeyword = self._extract_keyword(self.current_line, offset=len("CONVECTION"))
        
        if subkeyword == "ON":
            self.atmosphere.IFCONV = 1
            # Try to extract MIXLTH value
            value = self._extract_float(self.current_line, offset=self.current_line.find("ON") + 2)
            if value is not None:
                self.atmosphere.MIXLTH = value
        elif subkeyword == "OFF":
            self.atmosphere.IFCONV = 0
            self.atmosphere.MIXLTH = 1.0
    
    def _handle_turbulence(self):
        """Handle TURBULENCE keyword.
        
        Fortran (atlas7v.for line 2000):
            IFTURB=1
            TRBFDG=FREEFF(CARD)
            TRBPOW=FREEFF(CARD)
            TRBSND=FREEFF(CARD)
            TRBCON=FREEFF(CARD)
        """
        subkeyword = self._extract_keyword(self.current_line, offset=len("TURBULENCE"))
        
        if subkeyword == "ON":
            self.atmosphere.IFTURB = 1
            # Extract parameters after ON
            values = self._extract_floats(self.current_line, 4, 
                                         offset=self.current_line.find("ON") + 2)
            if len(values) >= 4:
                self.atmosphere.TRBFDG = values[0]
                self.atmosphere.TRBPOW = values[1]
                self.atmosphere.TRBSND = values[2]
                self.atmosphere.TRBCON = values[3]
        elif subkeyword == "OFF":
            self.atmosphere.IFTURB = 0
            self.atmosphere.TRBFDG = 0.0
            self.atmosphere.TRBPOW = 0.0
            self.atmosphere.TRBSND = 0.0
            self.atmosphere.TRBCON = 0.0
    
    def _handle_abundance(self):
        """Handle ABUNDANCE keyword with SCALE, CHANGE, or TABLE options.
        
        Fortran (atlas7v.for line 800-830):
            MIAC=IWORDF(CARD)
            IF(MIAC.EQ.35762836)GO TO 810  ! SCALE
            IF(MIAC.EQ.223095242)GO TO 820 ! CHANGE
            IF(MIAC.EQ.37537060)GO TO 830  ! TABLE
        
        Note: A single line can contain both SCALE and CHANGE keywords.
        Example: ABUNDANCE SCALE 1.0 ABUNDANCE CHANGE 1 0.91 2 0.08
        We process all of them on this line.
        """
        # Initialize ABUND if needed
        if self.atmosphere.ABUND is None:
            self.atmosphere.ABUND = [0.0] * 99
        
        line_upper = self.current_line.upper()
        
        # Handle SCALE keyword (if present)
        scale_pos = line_upper.find("SCALE")
        if scale_pos >= 0:
            value = self._extract_float(self.current_line, offset=scale_pos + len("SCALE"))
            if value is not None:
                self._scale_value = value
        
        # Handle CHANGE keyword (if present) - can appear multiple times on one line
        # Look for all ABUNDANCE keywords followed by CHANGE
        change_pos = line_upper.find("CHANGE")
        if change_pos >= 0:
            # Find where the data starts (after CHANGE keyword)
            data_start = change_pos + len("CHANGE")
            remaining_line = self.current_line[data_start:]
            
            # Parse pairs of (element_index, abundance)
            parts = remaining_line.split()
            i = 0
            while i < len(parts):
                # Stop if we hit another keyword
                upper_part = parts[i].upper()
                if upper_part in ["ABUNDANCE", "SCALE", "TABLE", "READ", "END"]:
                    # If we found another ABUNDANCE keyword, recursively handle it
                    if upper_part == "ABUNDANCE" and i + 1 < len(parts):
                        rest_of_line = " ".join(parts[i:])
                        self.current_line = rest_of_line
                        self._handle_abundance()
                        return  # Done with this line
                    else:
                        break  # Stop parsing this keyword
                
                try:
                    iz = int(parts[i])
                    val = float(parts[i + 1])
                    if 1 <= iz <= 99:
                        self.atmosphere.ABUND[iz - 1] = val
                    i += 2
                except (ValueError, IndexError):
                    i += 1
    
    def _handle_pressure(self):
        """Handle PRESSURE keyword.
        
        Fortran (atlas7v.for line 2400):
            IFPRES=1 or IFPRES=0
        """
        subkeyword = self._extract_keyword(self.current_line, offset=len("PRESSURE"))
        
        if subkeyword == "ON":
            self.atmosphere.IFPRES = 1
        elif subkeyword == "OFF":
            self.atmosphere.IFPRES = 0
    
    def _handle_correction(self):
        """Handle CORRECTION keyword.
        
        Fortran (atlas7v.for line 2500):
            IFCORR=1 or IFCORR=0
        """
        subkeyword = self._extract_keyword(self.current_line, offset=len("CORRECTION"))
        
        if subkeyword == "ON":
            self.atmosphere.IFCORR = 1
        elif subkeyword == "OFF":
            self.atmosphere.IFCORR = 0
    
    def _handle_surface(self):
        """Handle SURFACE keyword.
        
        Fortran (atlas7v.for line 2300):
            Keywords: INTENSITY, FLUX, OFF
        """
        subkeyword = self._extract_keyword(self.current_line, offset=len("SURFACE"))
        
        if subkeyword == "FLUX":
            self.atmosphere.IFSURF = 1
        elif subkeyword == "INTENSITY":
            self.atmosphere.IFSURF = 2
        elif subkeyword == "OFF":
            self.atmosphere.IFSURF = 0
    
    def _handle_read(self):
        """Handle READ keyword - reads data arrays.
        
        Fortran (atlas7v.for line 1100):
            Keywords: MOLECULES, DECK6, FREQUENCIES, DEPARTURE COEFFICIENTS, etc.
        
        For DECK6:
            READ DECK6 <nrhox> <RHOX,T,P,XNE,ABROSS,ACCRAD,VTURB,...>
            <nrhox rows of data>
        """
        subkeyword = self._extract_keyword(self.current_line, offset=len("READ"))
        
        if subkeyword == "MOLECULES":
            # Read molecular abundances (not fully implemented)
            pass
        elif subkeyword == "DECK6":
            self._read_deck6()
        elif subkeyword == "FREQUENCIES":
            # Skip frequency data
            pass
        elif "DEPARTURE" in self.current_line:
            # Skip NLTE departure coefficients
            pass
    
    def _read_deck6(self):
        """Read DECK6 format data (atmosphere structure).
        
        Format:
            READ DECK6 <nrhox> <column1> <column2> ... <columnN>
            <nrhox rows of float data>
        """
        # Extract NRHOX (number of depth points)
        parts = self.current_line.split()
        
        try:
            nrhox = int(parts[parts.index("DECK6") + 1])
        except (ValueError, IndexError):
            return
        
        # Find where column names start (after "READ" "DECK6" and NRHOX)
        # Column names can be comma-separated or space-separated
        deck6_idx = self.current_line.find("DECK6")
        col_spec = self.current_line[deck6_idx + len("DECK6"):].strip()
        
        # Skip the NRHOX value
        for part in col_spec.split():
            try:
                int(part)
                col_spec = col_spec.replace(part, "", 1).strip()
                break
            except ValueError:
                pass
        
        # Parse column names (comma-separated or space-separated)
        if ',' in col_spec:
            columns = [c.strip() for c in col_spec.split(',')]
        else:
            columns = col_spec.split()
        
        # Map column names to atmosphere attributes
        column_map = {
            "RHOX": "RHOX",
            "T": "T",
            "P": "P",
            "XNE": "XNE",
            "ABROSS": "ABROSS",
            "PRAD": "PRAD",    # Radiation pressure (read from file)
            "ACCRAD": "PRAD",  # Alias: old file format uses ACCRAD header for PRAD data
            "VTURB": "VTURB",
            "FLXRAD": "FLXRAD",
            "VCONV": "VCONV",
            "VELSND": "VELSND",
        }
        
        # Initialize arrays
        data = {}
        for col_name in columns:
            col_upper = col_name.upper()
            if col_upper in column_map:
                data[column_map[col_upper]] = []
        
        # Read NRHOX lines of data
        for _ in range(nrhox):
            line = self.file.readline()
            if not line:
                break
            
            self.line_number += 1
            
            values = []
            for item in line.split():
                try:
                    values.append(float(item))
                except ValueError:
                    pass
            
            # Assign values to columns in order
            for col_idx, col_name in enumerate(columns):
                col_upper = col_name.upper()
                if col_upper in column_map and col_idx < len(values):
                    mapped_name = column_map[col_upper]
                    data[mapped_name].append(values[col_idx])
        
        # Store in atmosphere object
        self.atmosphere.NRHOX = nrhox
        
        for col_name, values in data.items():
            if len(values) == nrhox:
                setattr(self.atmosphere, col_name, _make_tensor(values, "float64"))
    
    def _handle_lte(self):
        """Handle LTE keyword - set LTE mode.
        
        Fortran (atlas7v.for line 1200):
            NLTEON=0
        """
        self.atmosphere.NLTEON = 0
    
    def _handle_nlte(self):
        """Handle NLTE keyword - set non-LTE mode.
        
        Fortran (atlas7v.for line 1300):
            NLTEON=1
        """
        self.atmosphere.NLTEON = 1
    
    def _handle_pradk(self):
        """Handle PRADK keyword - radiation pressure constant.
        
        This is typically a scalar global parameter that appears at the end
        of the atmosphere file. Format: PRADK <value>
        
        Example from output_synthe.out:
            PRADK 1.4802E+00
        """
        value = self._extract_float(self.current_line, offset=len("PRADK"))
        if value is not None:
            # Store as scalar - PRADK in the file is a single value, not per-depth
            self.atmosphere.PRADK0 = value
    
    # ========== Parsing Utilities (Implementing Fortran FREEFF logic) ==========
    
    def _extract_keyword(self, line: str, offset: int = 0) -> Optional[str]:
        """Extract the first keyword (alphanumeric word) from a line.
        
        Implements Fortran IWORDF logic for Machine-Independent Alphameric Code.
        
        Args:
            line: Input line to parse
            offset: Character position to start searching
        
        Returns:
            First keyword found, or None
        """
        # Skip leading spaces
        start = offset
        while start < len(line) and line[start].isspace():
            start += 1
        
        if start >= len(line):
            return None
        
        # Extract alphanumeric word
        end = start
        while end < len(line) and (line[end].isalnum() or line[end] in "._-"):
            end += 1
        
        return line[start:end].upper() if end > start else None
    
    def _extract_float(self, line: str, offset: int = 0) -> Optional[float]:
        """Extract a floating-point number from a line.
        
        Implements Fortran FREEFF logic. Handles:
        - Decimal: 1.23
        - Scientific: 1.23e+02, 1.23D+02
        - Integer: 5
        
        Args:
            line: Input line
            offset: Character position to start searching (will skip leading spaces)
        
        Returns:
            Parsed float, or None if not found
        """
        # Skip spaces from offset
        start = offset
        while start < len(line) and line[start].isspace():
            start += 1
        
        if start >= len(line):
            return None
        
        # Extract potential number (including sign, digits, decimal point, exponent)
        # Allow +/- sign at the beginning
        end = start
        if end < len(line) and line[end] in "+-":
            end += 1
        
        # Now extract digits, decimal point, and exponent
        while end < len(line) and line[end] in "0123456789.eEdD":
            end += 1
        
        # Handle exponent sign (e+ or e- or E+ or E-)
        if end < len(line) and end > start and line[end - 1] in "eEdD":
            if end < len(line) and line[end] in "+-":
                end += 1
                # Extract exponent digits
                while end < len(line) and line[end] in "0123456789":
                    end += 1
        
        if end == start or (end == start + 1 and line[start] in "+-"):
            return None
        
        num_str = line[start:end]
        
        try:
            # Replace 'D' exponent notation with 'e' for Python
            num_str = num_str.replace('D', 'e').replace('d', 'e')
            return float(num_str)
        except ValueError:
            return None
    
    def _extract_floats(self, line: str, count: int, offset: int = 0) -> List[float]:
        """Extract multiple floating-point numbers from a line.
        
        Args:
            line: Input line
            count: Number of floats to extract
            offset: Character position to start searching
        
        Returns:
            List of parsed floats (may be shorter if fewer than count available)
        """
        values = []
        current_offset = offset
        
        for _ in range(count):
            value = self._extract_float(line, current_offset)
            if value is None:
                break
            values.append(value)
            # Move past this number to find the next one
            # Find where this number ended
            start = current_offset
            while start < len(line) and line[start].isspace():
                start += 1
            
            if start >= len(line):
                break
            
            # Skip the sign if present
            if start < len(line) and line[start] in "+-":
                start += 1
            
            # Skip digits, decimal, exponent
            while start < len(line) and line[start] in "0123456789.eEdD":
                start += 1
            
            current_offset = start
        
        return values
    
    def _finalize_atmosphere(self):
        """Finalize the atmosphere object after reading.
        
        Converts data types and calls Atmosphere.update() to compute physics-based quantities.
        """
        # Convert ABUND list to tensor if it exists as a list
        if self.atmosphere.ABUND is not None and isinstance(self.atmosphere.ABUND, list):
            self.atmosphere.ABUND = _make_tensor(self.atmosphere.ABUND, "float64")
        
        # Ensure arrays are torch tensors or lists
        if self.atmosphere.RHOX is None and self.atmosphere.NRHOX > 0:
            self.atmosphere.RHOX = _make_tensor([0.0] * self.atmosphere.NRHOX, "float64")
        
        # Compute all physics-based derived quantities (FLUX, GLOG, PRADK, etc.)
        self.atmosphere.update()
